"""Temporary script to append manual Claude judgments to a CUAD cell results.jsonl.
Modified in-place per run. Not committed.
"""
import json
import sys


def append(cell_dir: str, prefix: str, judgments):
    fpath = f"results/stage3/judge_queue/{cell_dir}/results.jsonl"
    with open(fpath, "a", encoding="utf-8") as fh:
        for q, score, rat in judgments:
            fh.write(json.dumps({"qid": prefix + q, "judge_score": score, "rationale": rat}, ensure_ascii=False) + "\n")
    n = 0
    total = 0.0
    with open(fpath, encoding="utf-8") as fh:
        for line in fh:
            if line.strip():
                n += 1
                total += json.loads(line)["judge_score"]
    print(f"{cell_dir}: now {n} judgments, mean={total/n:.4f}")


